export function isEnglishLanguage(language) {
  return String(language || "").toLowerCase().startsWith("en");
}

export function displayText(value, language) {
  if (!isEnglishLanguage(language) || value == null) return value;
  let text = String(value);
  if (EXACT_EN[text]) return EXACT_EN[text];

  Object.entries(DAY_LABELS).forEach(([tr, labels]) => {
    text = text.replace(new RegExp(tr, "g"), labels.en);
  });

  for (const [from, to] of PHRASE_EN) {
    text = text.split(from).join(to);
  }
  for (const [from, to] of Object.entries(WORD_EN).sort((a, b) => b[0].length - a[0].length)) {
    text = text.split(from).join(to);
  }

  text = text.replace(/(\d+)\. Hafta/g, "Week $1");
  text = text.replace(/(\d+)\. haftayı tamamladım/g, "I completed week $1");
  return text;
}

export function displayDay(value, language) {
  if (!isEnglishLanguage(language)) return value;
  return DAY_LABELS[value]?.en || displayText(value, language);
}

export function displayDayShort(value, language) {
  if (!isEnglishLanguage(language)) return String(value || "").substring(0, 3).toUpperCase();
  return DAY_LABELS[value]?.shortEn || displayText(String(value || "").substring(0, 3), language).toUpperCase();
}

export function displayMuscleCode(value, language) {
  if (!isEnglishLanguage(language)) return value;
  return MUSCLE_CODE_EN[String(value || "").toUpperCase()] || displayText(value, language);
}
